import {readFileSync,writeFileSync,existsSync,mkdirSync} from 'node:fs';
import {resolve,dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const assert=(value,message)=>{if(!value)throw new Error(message);};

/** Preserve the original twenty rows and one set of option/cap data per weapon.
 * The public table uses local pattern IDs; the SHT byte offsets remain evidence
 * of the original records. No stone inventory or selection owner is imported. */
export function normalizeTouhouWeaponData(source,character,weapon){
  assert(character===0||character===1,'Character must be 0 or 1');
  assert(Number.isInteger(weapon)&&weapon>=0&&weapon<8,'Weapon must be an integer from 0 through 7');
  assert(source.maxPower===4&&source.patterns.length===160,'Expected the original eight twenty-pattern weapon profiles');
  for(const key of ['damageCaps','optionScripts','fullPowerScripts','offsets'])assert(source[key].length===8,`Expected eight ${key} records`);
  return {...source,format:'ts-stg-touhou-shots',character,profile:`weapon-${weapon}`,
    damageCaps:[source.damageCaps[weapon]],optionScripts:[source.optionScripts[weapon]],
    fullPowerScripts:[source.fullPowerScripts[weapon]],offsets:[source.offsets[weapon]],
    patterns:source.patterns.slice(weapon*20,weapon*20+20),
    source:{...source.source,selection:`Weapon ${weapon}; original patterns ${weapon*20}..${weapon*20+19} mapped to local 0..19; main/unfocused/focused/active groups retained`}};
}

export function buildTouhouWeaponData(source=join(root,'games/demo/assets')){
  return ['pl00','pl01'].map((name,character)=>{
    const original=JSON.parse(readFileSync(join(source,'shots',`${name}.json`),'utf8'));
    return Array.from({length:8},(_,weapon)=>normalizeTouhouWeaponData(original,character,weapon));
  });
}

export function writeTouhouWeaponData({source=join(root,'games/demo/assets'),out=join(root,'packages/thlib/src/touhou/weapon-data.ts'),checkOnly=false}={}){
  const data=buildTouhouWeaponData(source);
  const bytes=Buffer.from(`import type {TouhouSht} from './shot-data.js';
// Original numeric weapon records; no executable code, stone selection or inventory.
// Generated by tools/import-touhou-weapon-data.mjs from the original decoded SHT.
const freeze=<T>(value:T):T=>{if(value&&typeof value==='object'){for(const item of Object.values(value))freeze(item);Object.freeze(value);}return value;};
export type TouhouWeaponIndex=0|1|2|3|4|5|6|7;
export const TOUHOU_WEAPON_DATA=freeze<TouhouSht[][]>(${JSON.stringify(data)});
/** Select one complete weapon: main, unfocused, focused and active rows, each with power levels 0..4. */
export function getTouhouWeaponData(character:0|1|'reimu'|'marisa',weapon:TouhouWeaponIndex):TouhouSht{
  const id=character==='reimu'?0:character==='marisa'?1:character;
  if(id!==0&&id!==1)throw new RangeError('Character must be 0/reimu or 1/marisa');
  if(!Number.isInteger(weapon)||weapon<0||weapon>7)throw new RangeError('Weapon must be an integer from 0 through 7');
  return TOUHOU_WEAPON_DATA[id][weapon];
}
`);
  if(checkOnly)assert(existsSync(out)&&readFileSync(out).equals(bytes),'Generated weapon-data.ts differs from the original SHT records');
  else{mkdirSync(dirname(out),{recursive:true});writeFileSync(out,bytes);}
  return {output:resolve(out),characters:data.length,weapons:data.flat().length,patterns:data.flat().reduce((sum,weapon)=>sum+weapon.patterns.length,0),verified:checkOnly};
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const args=process.argv.slice(2),options={};
  for(let i=0;i<args.length;i++){if(args[i]==='--source')options.source=args[++i];else if(args[i]==='--out')options.out=args[++i];else if(args[i]==='--check')options.checkOnly=true;else throw new Error(`Unknown option ${args[i]}`);}
  console.log(JSON.stringify(writeTouhouWeaponData(options),null,2));
}
