import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {verifyBulletVectors} from '../native/tests/bullet-compare.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const oracle=process.argv[2]??path.join(root,'build/Release/tsstg-bullet-oracle.exe');
const output=spawnSync(oracle,[],{encoding:'utf8',maxBuffer:8*1024*1024});
if(output.status!==0)throw new Error(output.stderr||output.error||'Bullet reference harness failed');
const vectors=JSON.parse(output.stdout);console.log('Node',verifyBulletVectors(vectors));
fs.writeFileSync(path.join(root,'tests/fixtures/th20-bullet-vectors.json'),JSON.stringify(vectors));
const host=process.argv[3]??path.join(root,'build/Release/ts-stg.exe');
const native=spawnSync(host,['native/tests/bullet-quickjs.js','--root',root,'--headless','--frames','1'],{encoding:'utf8'});
if(native.status!==0)throw new Error(native.stderr||'QuickJS bullet verification failed');console.log(native.stdout.trim());
