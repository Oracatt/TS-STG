// Real native QuickJS host parity for all 29 RushBoss phases x four difficulties.
// No original game EXE, game resource import, GPU or audio is involved.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL,fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sourceFiles=['games/rushboss/src/runtime.js','games/rushboss/src/player-adapter.js','games/rushboss/src/random.js',
  'games/rushboss/src/sunny.js','games/rushboss/src/monstone.js','games/rushboss/src/artia.js',
  'games/rushboss/src/bullet-styles.js','packages/thlib/src/world.js',
  'packages/thlib/src/bullet-presets.js','packages/thlib/src/bullets.js',
  'packages/thlib/src/lasers.js','packages/thlib/src/math.js','packages/thlib/src/bomb-geometry.js',
  'games/rushboss/src/bullet-visuals.js',
  ...fs.readdirSync(path.join(root,'packages/thlib/src/touhou')).filter(file=>file.endsWith('.js')).sort().map(file=>'packages/thlib/src/touhou/'+file)];
const hashSources=()=>Object.fromEntries(sourceFiles.map(file=>
  [file,createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex')]));
const sourceHashes=hashSources();
const out=path.join(root,'build/rushboss-runtime');fs.mkdirSync(out,{recursive:true});
const fixturePath=path.join(out,'quickjs-fixture.js');
const fixtureSource=`// Generated by tools/verify-rushboss-quickjs.mjs; portable ESM native fixture.
import { RushBattle } from '../../games/rushboss/src/runtime.js';
import { sunnyPhases } from '../../games/rushboss/src/sunny.js';
import { monstonePhases } from '../../games/rushboss/src/monstone.js';
import { artiaPhases } from '../../games/rushboss/src/artia.js';
export const CASE_FRAMES=600;
export function createRushRuntimeFixture(){
  const cases=[];
  for(const [boss,phases]of[['sunny',sunnyPhases],['monstone',monstonePhases],['artia',artiaPhases]])
    for(let difficulty=0;difficulty<4;difficulty++)for(let index=0;index<phases.length;index++)
      cases.push({boss,phases,difficulty,index});
  const results=[];let caseIndex=0,localFrame=0,battle=null,updates=0;
  function begin(){const c=cases[caseIndex];battle=new RushBattle(c.phases,{boss:c.boss,difficulty:c.difficulty,
    character:0,seed:5489,practice:true,spellIndex:c.index,invincible:true});localFrame=0;}
  begin();
  return{
    update(){
      if(caseIndex>=cases.length)return;
      battle.update(0);localFrame++;updates++;
      if(localFrame===CASE_FRAMES){results.push(battle.snapshot());caseIndex++;if(caseIndex<cases.length)begin();}
    },
    render(){return [];},
    snapshot(){return{cases:cases.length,caseFrames:CASE_FRAMES,totalUpdates:updates,complete:caseIndex===cases.length,
      seed:5489,character:0,invincible:true,results};}
  };
}
globalThis.__tsstg_game=createRushRuntimeFixture();
`;
fs.writeFileSync(fixturePath,fixtureSource);
const {createRushRuntimeFixture,CASE_FRAMES}=await import(pathToFileURL(fixturePath).href);
const totalFrames=29*4*CASE_FRAMES,started=performance.now(),fixture=createRushRuntimeFixture();
for(let frame=0;frame<totalFrames;frame++){fixture.update();fixture.render();}
// The native snapshot crosses the JSON boundary (which represents -0 as 0).
// Compare the same serialized representation from both runtimes, without a
// numeric tolerance or rounding of finite gameplay values.
const node=JSON.parse(JSON.stringify(fixture.snapshot())),nodeMs=Math.round(performance.now()-started);
assert.equal(node.complete,true);assert.equal(node.results.length,116);assert.equal(node.totalUpdates,totalFrames);
console.log(`Node: 116 phases x ${CASE_FRAMES} frames completed (${nodeMs} ms)`);
assert.deepEqual(hashSources(),sourceHashes,'Simulation source changed during the Node portion of parity verification.');
const binary=[process.env.TSSTG_BINARY,'build/Release/ts-stg.exe','build/RelWithDebInfo/ts-stg.exe',
  'build/Debug/ts-stg.exe','build/ts-stg.exe','build/ts-stg'].filter(Boolean).map(file=>path.resolve(root,file)).find(fs.existsSync);
if(!binary)throw Error('Build the native TS-STG host before verifying QuickJS.');
const nativeOutput=path.join(out,'quickjs-snapshot.json'),nativeStart=performance.now();
const child=spawn(binary,[path.relative(root,fixturePath).replaceAll('\\','/'),'--root',root,
  '--headless','--frames',String(totalFrames),'--snapshot',nativeOutput],{cwd:root,stdio:['ignore','pipe','pipe']});
let stdout='',stderr='';child.stdout.on('data',chunk=>stdout+=chunk);child.stderr.on('data',chunk=>stderr+=chunk);
const timer=setTimeout(()=>child.kill(),300000);
const status=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('close',resolve);});clearTimeout(timer);
assert.equal(status,0,`Native QuickJS fixture failed:\n${stdout}\n${stderr}`);
const native=JSON.parse(fs.readFileSync(nativeOutput,'utf8'));
assert.deepEqual(hashSources(),sourceHashes,'Simulation source changed during the native QuickJS parity verification.');
assert.deepEqual(native,node,'Node/QuickJS snapshots differ; no numeric tolerance is permitted.');
const report={scope:'29 phases x four difficulties, 600 frames per case, native headless QuickJS host',
  originalExecutableRun:false,originalFullStateEquivalenceVerified:false,assetOrShaderDependency:false,
  snapshotParity:'strict (no numeric tolerance)',cases:116,caseFrames:CASE_FRAMES,totalFrames,
  sourceHashes,sourceStableDuringVerification:true,
  seed:5489,character:0,invincible:true,nodeMs,quickjsMs:Math.round(performance.now()-nativeStart),
  nativeBinarySha256:createHash('sha256').update(fs.readFileSync(binary)).digest('hex'),
  fixtureSha256:createHash('sha256').update(fixtureSource).digest('hex'),
  results:node.results.map(r=>({boss:r.boss,difficulty:r.difficulty,phase:r.phase,phaseFrames:r.phaseFrame,
    spawned:r.statistics.spawned,lasers:r.statistics.lasers,peak:r.statistics.peak,spawnHash:r.spawnHash,
    randomCalls:r.randomCalls,position:r.position,passed:true})),passed:true};
const reportPath=path.join(root,'reports/rushboss/quickjs.json');fs.mkdirSync(path.dirname(reportPath),{recursive:true});
fs.writeFileSync(reportPath,JSON.stringify(report,null,2)+'\n');
console.log(`PASS: ${report.cases} Node/QuickJS cases matched exactly; ${reportPath}`);
